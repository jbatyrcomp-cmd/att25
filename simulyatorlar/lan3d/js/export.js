/* ---------- Yordamchi: fayl yuklab olish ---------- */
function downloadBlob(filename, content, type = 'text/plain') {
  const blob = new Blob([content], { type });
  const url  = URL.createObjectURL(blob);
  const a    = Object.assign(document.createElement('a'), { href: url, download: filename });
  document.body.appendChild(a);
  a.click();
  document.body.removeChild(a);
  URL.revokeObjectURL(url);
}

/* ==========================================================================
   1. PNG Screenshot (Three.js renderer orqali)
   ========================================================================== */
function captureSceneSnapshot() {
  // preserveDrawingBuffer: true bo'lishi kerak; agarda yo'q bo'lsa ogohlantirish
  try {
    renderer.render(scene, camera);
    const dataUrl = renderer.domElement.toDataURL('image/png');
    if (dataUrl === 'data:,') {
      toast('⚠️ Screenshot olish uchun renderer.preserveDrawingBuffer=true kerak');
      return;
    }
    downloadBlob('lan3d_screenshot.png', dataUrl); // base64 DataURL download
    // Ma'lumot URL uchun maxsus yondashuv
    const a    = document.createElement('a');
    a.href     = dataUrl;
    a.download = 'lan3d_screenshot.png';
    a.click();
    toast('📷 Screenshot saqlandi: lan3d_screenshot.png');
  } catch(e) {
    toast('⚠️ Screenshot xatosi: ' + e.message);
  }
}

/* ==========================================================================
   2. Cisco IOS Config Eksport (.txt)
   ========================================================================== */
function generateCiscoConfig(devId) {
  const dev = devices.get(devId);
  if (!dev) return '';
  const t = dev.type;
  const now = new Date().toISOString().slice(0, 16).replace('T', ' ');
  let cfg = `!\n! Generated by LAN 3D Simulator\n! Date: ${now}\n! Device: ${dev.name} (${t})\n!\n`;

  if (t === 'router') {
    cfg += `hostname ${dev.name}\n!\n`;
    cfg += `no ip domain-lookup\n`;
    cfg += `ip routing\n!\n`;
    // Interfacelar
    const connectedConns = [...connections.values()].filter(c => c.a === devId || c.b === devId);
    connectedConns.forEach((c, i) => {
      const otherId = c.a === devId ? c.b : c.a;
      const other   = devices.get(otherId);
      cfg += `interface GigabitEthernet0/${i}\n`;
      cfg += ` description To_${other ? other.name.replace(/\s/g,'_') : otherId}\n`;
      cfg += ` ip address ${dev.ip} ${dev.mask}\n`;
      cfg += ` no shutdown\n!\n`;
    });
    cfg += `interface GigabitEthernet0/${connectedConns.length}\n description Management\n ip address ${dev.ip} ${dev.mask}\n no shutdown\n!\n`;
    cfg += `ip route 0.0.0.0 0.0.0.0 ${dev.gw || '0.0.0.0'}\n!\n`;
    cfg += `line con 0\n transport input none\n!\nend\n`;

  } else if (t === 'switch') {
    cfg += `hostname ${dev.name}\n!\n`;
    cfg += `no ip domain-lookup\n!\n`;
    cfg += `spanning-tree mode pvst\n!\n`;
    const connectedConns = [...connections.values()].filter(c => c.a === devId || c.b === devId);
    connectedConns.forEach((c, i) => {
      const otherId = c.a === devId ? c.b : c.a;
      const other   = devices.get(otherId);
      cfg += `interface FastEthernet0/${i + 1}\n`;
      cfg += ` description To_${other ? other.name.replace(/\s/g,'_') : otherId}\n`;
      cfg += ` switchport mode access\n`;
      cfg += ` switchport access vlan 1\n`;
      cfg += ` spanning-tree portfast\n`;
      cfg += ` no shutdown\n!\n`;
    });
    cfg += `interface Vlan1\n ip address ${dev.ip} ${dev.mask}\n no shutdown\n!\n`;
    cfg += `ip default-gateway ${dev.gw || '192.168.1.1'}\n!\n`;
    cfg += `line con 0\n!\nend\n`;

  } else {
    // PC/Laptop/Server uchun
    cfg += `! Host: ${dev.name}\n`;
    cfg += `! IP Address  : ${dev.ip}\n`;
    cfg += `! Subnet Mask : ${dev.mask}\n`;
    cfg += `! Gateway     : ${dev.gw}\n`;
    cfg += `! DNS         : ${dev.dns || '8.8.8.8'}\n`;
    cfg += `! MAC Address : ${dev.mac}\n`;
    cfg += `!\n! Network Interface Configuration:\n`;
    cfg += `!   ipconfig set LAN0 static ${dev.ip} ${dev.mask} ${dev.gw}\n`;
    cfg += `!\nend\n`;
  }
  return cfg;
}

function exportCiscoConfig(devId) {
  if (!devId) {
    // Barcha qurilmalar
    let fullCfg = '';
    devices.forEach(d => {
      fullCfg += generateCiscoConfig(d.id);
      fullCfg += '\n! ' + '='.repeat(60) + '\n\n';
    });
    downloadBlob('lan3d_full_config.txt', fullCfg);
    toast('📄 Barcha qurilmalar konfiguratsiyasi yuklandi');
  } else {
    const dev = devices.get(devId);
    const cfg = generateCiscoConfig(devId);
    downloadBlob(`${dev.name.replace(/\s/g,'_')}_config.txt`, cfg);
    toast(`📄 ${dev.name} konfiguratsiyasi yuklandi`);
  }
}

