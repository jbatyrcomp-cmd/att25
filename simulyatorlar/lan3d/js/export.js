/* ==========================================================================
   4. 2D SVG Topologiya Diagrammasi
   ========================================================================== */
function exportTopologySvg() {
  const W = 900, H = 700, PAD = 60;
  const devList = [...devices.values()];
  if (devList.length === 0) { toast('⚠️ Sahnada qurilma yo\'q!'); return; }

  // 3D pozitsiyalarni 2D ga o'tkazish
  const xs = devList.map(d => d.group.position.x);
  const zs = devList.map(d => d.group.position.z);
  const minX = Math.min(...xs), maxX = Math.max(...xs);
  const minZ = Math.min(...zs), maxZ = Math.max(...zs);
  const scaleX = maxX === minX ? 1 : (W - PAD*2) / (maxX - minX);
  const scaleZ = maxZ === minZ ? 1 : (H - PAD*2) / (maxZ - minZ);

  function toSvgX(x) { return PAD + (x - minX) * scaleX; }
  function toSvgY(z) { return PAD + (z - minZ) * scaleZ; }

  const COLORS = { router:'#A78BFA', switch:'#38BDF8', server:'#FFB454', desktop:'#6FE3C4', laptop:'#34D399', phone:'#EC4899', printer:'#FBBF24', tablet:'#60A5FA' };

  const connLines = [...connections.values()].map(c => {
    const a = devices.get(c.a), b = devices.get(c.b);
    if (!a || !b) return '';
    const x1 = toSvgX(a.group.position.x), y1 = toSvgY(a.group.position.z);
    const x2 = toSvgX(b.group.position.x), y2 = toSvgY(b.group.position.z);
    const stroke = c.wireless ? '#4FC7E8' : '#444';
    const dash   = c.wireless ? 'stroke-dasharray="6 4"' : '';
    return `<line x1="${x1.toFixed(1)}" y1="${y1.toFixed(1)}" x2="${x2.toFixed(1)}" y2="${y2.toFixed(1)}" stroke="${stroke}" stroke-width="2" ${dash} opacity="0.6"/>`;
  }).join('\n');

  const devNodes = devList.map(d => {
    const x = toSvgX(d.group.position.x), y = toSvgY(d.group.position.z);
    const col = COLORS[d.type] || '#fff';
    return `
      <circle cx="${x.toFixed(1)}" cy="${y.toFixed(1)}" r="18" fill="${col}" fill-opacity="0.2" stroke="${col}" stroke-width="2"/>
      <text x="${x.toFixed(1)}" y="${(y+4).toFixed(1)}" text-anchor="middle" font-size="11" fill="${col}" font-family="Inter,sans-serif" font-weight="700">${d.type.slice(0,2).toUpperCase()}</text>
      <text x="${x.toFixed(1)}" y="${(y+34).toFixed(1)}" text-anchor="middle" font-size="10" fill="#E6EDF3" font-family="Inter,sans-serif">${escapeHtml(d.name)}</text>
      <text x="${x.toFixed(1)}" y="${(y+46).toFixed(1)}" text-anchor="middle" font-size="9" fill="#8B949E" font-family="JetBrains Mono,monospace">${d.ip}</text>
    `;
  }).join('\n');

  const svg = `<?xml version="1.0" encoding="UTF-8"?>
<svg xmlns="http://www.w3.org/2000/svg" width="${W}" height="${H}" viewBox="0 0 ${W} ${H}">
  <rect width="100%" height="100%" fill="#0D1117"/>
  <text x="20" y="26" font-size="14" fill="#6FE3C4" font-family="Inter,sans-serif" font-weight="800">🌐 LAN 3D — Network Topology Diagram</text>
  <text x="20" y="42" font-size="10" fill="#8B949E" font-family="Inter,sans-serif">${devices.size} qurilma · ${connections.size} ulanish · ${new Date().toLocaleString('uz-UZ')}</text>
  <g id="connections">${connLines}</g>
  <g id="devices">${devNodes}</g>
</svg>`;

  downloadBlob('lan3d_topology.svg', svg, 'image/svg+xml');
  toast('🗺️ 2D Topologiya diagrammasi yuklandi: lan3d_topology.svg');
}

/* ---------- Export Dropdown Ochish ---------- */
function openExportDropdown(e) {
  if (e && typeof e.stopPropagation === 'function') e.stopPropagation();
  ['topoMenu', 'roomMenu', 'cableMenu'].forEach(id => {
    const el = document.getElementById(id);
    if (el) el.classList.remove('show');
  });
  const dd = document.getElementById('exportDropdown');
  if (dd) dd.classList.toggle('show');
}

document.addEventListener('click', (e) => {
  const dd  = document.getElementById('exportDropdown');
  const btn = document.getElementById('exportBtn');
  if (dd && !dd.contains(e.target) && (!btn || !btn.contains(e.target))) {
    dd.classList.remove('show');
  }
});

if (typeof document !== 'undefined') {
  const initExportItems = () => {
    const dd = document.getElementById('exportDropdown');
    if (dd) {
      dd.querySelectorAll('.topo-item').forEach(item => {
        item.addEventListener('click', () => dd.classList.remove('show'));
      });
    }
  };
  if (document.readyState === 'loading') {
    document.addEventListener('DOMContentLoaded', initExportItems);
  } else {
    initExportItems();
  }
}
